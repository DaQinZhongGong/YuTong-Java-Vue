# Sort keys alphabetically and write JSON
function Write-JsonFile($keys, $filePath) {
    $sortedKeys = $keys.Keys | Sort-Object
    $lines = @("{")
    for ($i = 0; $i -lt $sortedKeys.Count; $i++) {
        $k = $sortedKeys[$i]
        $v = $keys[$k]
        # Escape backslash and double quotes in value
        $escapedV = $v -replace '\\', '\\' -replace '"', '\"'
        $comma = if ($i -lt $sortedKeys.Count - 1) { "," } else { "" }
        $lines += "    `"$k`":  `"$escapedV`"$comma"
    }
    $lines += "}"
    $content = $lines -join "`r`n"
    [System.IO.File]::WriteAllText($filePath, $content, [System.Text.Encoding]::UTF8)
    Write-Host "Written $($sortedKeys.Count) keys to $filePath"
}

